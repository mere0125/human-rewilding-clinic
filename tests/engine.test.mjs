import test from 'node:test';
import assert from 'node:assert/strict';
import {CASE,volume,clearArea} from '../case.mjs';
import {thermalStep,makeDemo,metrics,simulate,quality,harmonic,parseCSV,toCSV,classify,sensitivity,HOUR,hourAt} from '../engine.mjs';
const near=(a,b,tol=1e-8)=>assert.ok(Math.abs(a-b)<tol,`${a} differs from ${b}`);
test('shared room dimensions give the registered volume and pane area',()=>{near(volume,31.104);near(clearArea,.642495);});
test('exact passive thermal response and equilibrium',()=>{
  near(thermalStep(25,10,0,40,4e6,3600),10+15*Math.exp(-40*3600/4e6));
  near(thermalStep(20,10,400,40,4e6,3600),20);
  near(thermalStep(20,10,100,0,1000,10),21);
});
test('harmonic fit recovers offset and amplitude under irregular sampling',()=>{
  const start=Date.parse('2026-10-13T00:00:00-04:00');
  const rows=Array.from({length:673},(_,i)=>{const h=i/4;return {t:start+h*HOUR,outdoor:18+5*Math.cos(2*Math.PI*(h-14)/24),indoor:22+2*Math.cos(2*Math.PI*(h-17)/24),hvac:null};}).filter((r,i)=>i%7!==0);
  const m=metrics(rows);near(m.out.amplitude,5);near(m.inside.amplitude,2);near(m.ratio,.4);near(m.lag,3);near(m.out.mean,18);assert.equal(m.duty,null);
});
test('non-orthogonal partial-window fit still recovers a known harmonic',()=>{
  const rows=Array.from({length:39},(_,i)=>({t:i*.37*HOUR,indoor:22+3*Math.sin(2*Math.PI*i*.37/24)}));
  const fit=harmonic(rows,'indoor');near(fit.mean,22);near(fit.amplitude,3);
});
test('conditioning duty is weighted by interval duration',()=>{
  const r=[0,1,1.5,2.5,3.5].map((h,i)=>({t:h*HOUR,indoor:20+i*.1,outdoor:15+i*.2,hvac:i===1?1:0}));
  near(metrics(r).duty,.5/3.5);
});
test('gaps are reported and excluded, never silently interpolated',()=>{
  const r=makeDemo().filter((r,i)=>i<100||i>108),q=quality(r);
  assert.equal(q.gaps,1);near(q.longestGap/HOUR,2.5);assert.ok(q.coverage<1);
  const s=simulate(r);assert.equal(s.resets,1);near(s[100].indoor,r[100].indoor);
});
test('demo is generated by the same baseline physics and not tuned to force a flag',()=>{
  const r=makeDemo(),b=simulate(r);r.forEach((row,i)=>near(row.indoor,b[i].indoor));
  const c=classify(metrics(r),CASE.audit);assert.equal(c.sufficient,true);assert.equal(c.flag,false);
});
test('permissions block a window even during the opening schedule',()=>{
  const r=makeDemo(),s=simulate(r,{permission:false});assert.ok(s.slice(0,-1).every(r=>r.window===0));
  const open=simulate(r,{permission:true});assert.ok(open.some(r=>r.window===1));
  open.slice(0,-1).filter(r=>r.window===1).forEach(r=>{const h=hourAt(r.t);assert.ok((h>=8&&h<10)||(h>=16&&h<18));assert.ok(r.outdoor>=14&&r.outdoor<=26);});
});
test('scenario changes never mutate source evidence',()=>{
  const r=makeDemo(),snapshot=JSON.stringify(r);simulate(r,{permission:true,deadband:3});assert.equal(JSON.stringify(r),snapshot);
});
test('unknown audit or absent conditioning prevents classification',()=>{
  const r=makeDemo();assert.equal(classify(metrics(r),{...CASE.audit,opening:'unknown'}).flag,null);
  assert.equal(classify(metrics(r.map(r=>({...r,hvac:null}))),CASE.audit).flag,null);
});
test('CSV blanks stay unknown, with timezone and duplicate protections',()=>{
  const r=parseCSV(toCSV(makeDemo()));assert.equal(r.length,673);assert.equal(r.at(-1).hvac,null);
  const blank='timestamp,outdoor_temp_c,indoor_temp_c\n'+Array.from({length:5},(_,i)=>`2026-10-13T0${i}:00:00-04:00,17,22`).join('\n');
  assert.equal(parseCSV(blank)[0].hvac,null);
  assert.throws(()=>parseCSV(blank.replaceAll('-04:00','')),/timezone/);
  assert.throws(()=>parseCSV(blank+'\n2026-10-13T00:00:00-04:00,17,22'),/Duplicate/);
  assert.throws(()=>parseCSV(blank.replace(',17,22',',,22')),/missing/);
});
test('81 paired sensitivity runs remain finite',()=>{
  const s=sensitivity(makeDemo(),{permission:true,deadband:2.5});assert.equal(s.length,81);assert.ok(s.every(r=>Number.isFinite(r.delta)));
});
test('controller time-step refinement remains within 0.2 K for this case',()=>{
  const r=makeDemo(),a=simulate(r,{permission:true,deadband:2.5},60),b=simulate(r,{permission:true,deadband:2.5},30);
  assert.ok(Math.max(...a.map((r,i)=>Math.abs(r.indoor-b[i].indoor)))<.2);
});
test('constant outdoor values and aliased daily samples do not create a ratio',()=>{
  const flat=makeDemo().map(r=>({...r,outdoor:18}));assert.equal(metrics(flat).ratio,null);
  const aliased=Array.from({length:5},(_,i)=>({t:i*24*HOUR,outdoor:15+i,indoor:22,hvac:null}));
  assert.equal(metrics(aliased).out,null);assert.equal(metrics(aliased).ratio,null);
});
